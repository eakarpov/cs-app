String grammaticalHelp(String label) {
  const terms = {
    'именительный':
        'Именительный падеж: кто? что? Часто обозначает действующее лицо или предмет.',
    'родительный':
        'Родительный падеж: кого? чего? Может обозначать принадлежность, часть или отсутствие.',
    'дательный':
        'Дательный падеж: кому? чему? Часто обозначает адресата действия.',
    'винительный':
        'Винительный падеж: кого? что? Часто обозначает предмет, на который направлено действие.',
    'творительный':
        'Творительный падеж: кем? чем? Может обозначать средство или участника действия.',
    'местный':
        'Местный падеж: о ком? о чём? В церковнославянском употребляется также в конструкциях, отличающихся от современных русских.',
    'звательный': 'Звательный падеж употребляется при обращении.',
    'двойственное': 'Двойственное число обозначает два лица или предмета.',
    'Имперфект':
        'Имперфект — прошедшее время, часто передающее длительное или повторявшееся действие.',
    'Аорист':
        'Аорист — прошедшее время, обычно представляющее действие как целое событие.',
    'Повелительное':
        'Повелительное наклонение передаёт просьбу, побуждение или повеление.',
    'Причастие':
        'Причастие соединяет признаки глагола и прилагательного; его падежные формы показаны в отдельной таблице.',
    'Инфинитив': 'Инфинитив — неопределённая форма глагола.',
  };
  final explanations = terms.entries
      .where((e) => label.contains(e.key))
      .map((e) => e.value)
      .toList();
  return explanations.isEmpty
      ? 'Грамматическая подпись указывает число, лицо, род или падеж данной формы. Значение формы в конкретном предложении зависит от контекста.'
      : explanations.join('\n\n');
}

